char	*ft_strstr(char *str, char *to_find)
{
	char	*s;
	char	*f;

	while (*str != '\0')
	{
		f = to_find;
		s = str;
		while ((*s != '\0') && (*f != '\0') && (*s == *f))
		{
			s++;
			f++;
		}
		if (*f == '\0')
		{
			return (str);
		}
		str++;
	}
	return (0);
}
